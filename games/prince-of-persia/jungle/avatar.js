function flipProgress() {
  const t = clamp((bridge.time - bridge.spinTime) / bridge.spinDuration, 0, 1);
  return bridge.spinFrom + (bridge.spinTo - bridge.spinFrom) * t;
}
function heroPose() {
  if (bridge.jumps) {
    const progress = Math.min(bridge.spinTo - .00001, flipProgress()),
      key = 'flip' + Math.floor(progress * 24) % 24;
    return {
      key,
      ax: .5,
      ay: .97,
      flip: false,
      frame: 0
    };
  }
  const angle = bridge.facing,
    abs = Math.abs(angle),
    frame = Math.floor(bridge.phase % 1 * 32),
    flip = angle > 0;
  const row = abs < .84 ? 3 : abs < 1.95 ? 0 : abs < 2.63 ? 1 : 2;
  let key,
    ax,
    ay,
    mirror = false;
  if (!bridge.moving && !bridge.jumps && bridgeArt.idle0) {
    key = 'idle' + (abs < .46 ? 0 : abs < .85 ? 3 : abs < 2.35 ? 1 : 2);
    [ax, ay] = otherBoots[key];
    mirror = flip && abs >= .46 && abs < 2.35;
  } else if (abs < .64) {
    const f = bridge.jumps ? bridge.vy > 0 ? 4 : 12 : frame;
    key = 'run' + f;
    ax = .52;
    ay = bootContacts[f][1];
  } else if (abs < 1.03) {
    key = 'turn' + (12 + Math.floor(frame / 8));
    ax = .5;
    ay = .993;
    mirror = flip;
  } else if (abs < 2.12) {
    key = 'side' + frame;
    ax = .5;
    ay = .994;
    mirror = flip;
  } else {
    key = 'turn' + (row * 4 + (bridge.jumps ? 2 : Math.floor(frame / 8)));
    [ax, ay] = otherBoots[key];
    mirror = flip && row !== 2;
  }
  return {
    key,
    ax: mirror ? 1 - ax : ax,
    ay,
    flip: mirror,
    frame
  };
}
function avatarPlacement(view) {
  const pose = heroPose(),
    im = bridgeArt[pose.key],
    s = bridge.d,
    x = trailCentre(s) + bridge.x,
    y = supportY(s, bridge.x) + bridge.y;
  const foot = view.screen(x, y, s),
    head = view.screen(x, y + 1.78, s),
    height = foot[1] - head[1],
    width = 1.78 * im.width / (im.height || 1) * view.focal / foot[2];
  return {
    mask: sideMasks[pose.key] || flipMasks[pose.key] || directionalMasks[pose.key] || poseMasks[pose.frame],
    flip: pose.flip,
    height,
    width,
    left: foot[0] - pose.ax * width,
    top: foot[1] - pose.ay * height,
    frame: pose.frame
  };
}
function coinContact(coin, index, view, previous) {
  const distance = coin.s - bridge.d;
  if (distance > 3.8 || distance < -2.0) return false;
  const [x, rawY] = view.proj(coin.s, coin.x, coin.y);
  const y = rawY + Math.sin(bridge.time * 2 + index) * 3 * view.unit;
  const a = avatarPlacement(view),
    radius = 14 * view.unit,
    mask = a.mask;
  // Use the actual opaque width of each band of the animated sprite.
  const top = Math.max(0, Math.floor((y - radius - a.top) / a.height * 24)),
    bottom = Math.min(23, Math.floor((y + radius - a.top) / a.height * 24));
  for (let row = top; row <= bottom; row++) {
    const l = a.flip ? 1 - mask[row * 2 + 1] : mask[row * 2],
      r = a.flip ? 1 - mask[row * 2] : mask[row * 2 + 1];
    if (r >= l && x + radius >= a.left + a.width * l && x - radius <= a.left + a.width * r) return true;
  }
  // Sweep the body through the coin plane between physics samples, including
  // lateral motion on a jump. This catch also tolerates small depth ambiguities.
  if (coin.s < Math.min(previous.d, bridge.d) - .86 || coin.s > Math.max(previous.d, bridge.d) + .86) return false;
  const t = clamp((coin.s - previous.d) / (bridge.d - previous.d || .00001), 0, 1);
  const hx = previous.x + (bridge.x - previous.x) * t,
    hy = previous.y + (bridge.y - previous.y) * t;
  return Math.abs(hx - coin.x) <= .69 && coin.y >= hy - .25 && coin.y <= hy + 1.99;
}
