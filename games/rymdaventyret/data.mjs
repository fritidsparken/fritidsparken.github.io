export function worldPosition(body, t = 0) {
  const a =
    body.phase +
    t * (body.parent ? 0.000015 : 0.0000015) * Math.pow(3600 / body.orbit, 0.5);
  const p = {
    x: Math.cos(a) * body.orbit,
    y: body.parent ? 60 : Math.sin(a * 2) * 80,
    z: Math.sin(a) * body.orbit,
  };
  if (body.parent) {
    const q = worldPosition(
      PLANETS.find((b) => b.id === body.parent),
      t,
    );
    p.x += q.x;
    p.y += q.y;
    p.z += q.z;
  }
  return p;
}
export function arrival(body, t = 0) {
  const p = worldPosition(body, t);
  return {
    x: p.x + body.r * 0.85,
    y: p.y + body.r * 0.45,
    z: p.z + body.r * 2.8 + 100,
  };
}
